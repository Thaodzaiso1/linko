BEGIN
  FOR t IN (SELECT table_name FROM user_tables 
            WHERE table_name IN ('AUDIT_LOG','KNOWS','PROJECT_MEMBERS',
                                 'REPORTS_TO','PROJECTS','EMPLOYEES','DEPARTMENTS')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
  END LOOP;
END;
