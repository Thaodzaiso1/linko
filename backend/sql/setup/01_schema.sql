-- ============================================================
-- 1. DEPARTMENTS
-- ============================================================
CREATE TABLE departments (
  department_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_name VARCHAR2(100) NOT NULL,
  location        VARCHAR2(100),
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- ============================================================
-- 2. EMPLOYEES (Vertex chính)
-- ============================================================
CREATE TABLE employees (
  employee_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name       VARCHAR2(150) NOT NULL,
  email           VARCHAR2(150) UNIQUE NOT NULL,
  title           VARCHAR2(100),
  department_id   NUMBER REFERENCES departments(department_id),
  hire_date       DATE DEFAULT SYSDATE,
  phone           VARCHAR2(20),
  status          VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','ON_LEAVE')),
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE INDEX idx_emp_dept ON employees(department_id);
CREATE INDEX idx_emp_name ON employees(full_name);

-- ============================================================
-- 3. PROJECTS (Vertex)
-- ============================================================
CREATE TABLE projects (
  project_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_name    VARCHAR2(150) NOT NULL,
  description     VARCHAR2(500),
  start_date      DATE,
  end_date        DATE,
  status          VARCHAR2(30) DEFAULT 'ACTIVE' 
                  CHECK (status IN ('PLANNING','ACTIVE','ON_HOLD','COMPLETED','CANCELLED')),
  department_id   NUMBER REFERENCES departments(department_id),
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- ============================================================
-- 4. REPORTS_TO (Edge: Manager hierarchy)
-- ============================================================
CREATE TABLE reports_to (
  employee_id     NUMBER PRIMARY KEY REFERENCES employees(employee_id),
  manager_id      NUMBER NOT NULL REFERENCES employees(employee_id),
  since_date      DATE DEFAULT SYSDATE,
  CONSTRAINT chk_not_self_manager CHECK (employee_id <> manager_id)
);

CREATE INDEX idx_reports_manager ON reports_to(manager_id);

-- ============================================================
-- 5. PROJECT_MEMBERS (Edge: Employee works on Project)
-- ============================================================
CREATE TABLE project_members (
  employee_id     NUMBER REFERENCES employees(employee_id),
  project_id      NUMBER REFERENCES projects(project_id),
  role            VARCHAR2(50) DEFAULT 'MEMBER',  -- LEAD, MEMBER, CONTRIBUTOR
  join_date       DATE DEFAULT SYSDATE,
  CONSTRAINT pk_project_members PRIMARY KEY (employee_id, project_id)
);

CREATE INDEX idx_pm_project ON project_members(project_id);

-- ============================================================
-- 6. KNOWS (Edge: Social connections - Follow / Friend / Mentor / Teammate)
-- ============================================================
CREATE TABLE knows (
  from_emp        NUMBER REFERENCES employees(employee_id),
  to_emp          NUMBER REFERENCES employees(employee_id),
  connection_type VARCHAR2(30) DEFAULT 'COLLEAGUE'
                  CHECK (connection_type IN ('COLLEAGUE','FRIEND','MENTOR','MENTEE','TEAMMATE','FOLLOW')),
  strength        NUMBER(3,2) DEFAULT 1.0 CHECK (strength BETWEEN 0 AND 5),
  since_date      DATE DEFAULT SYSDATE,
  notes           VARCHAR2(200),
  CONSTRAINT pk_knows PRIMARY KEY (from_emp, to_emp),
  CONSTRAINT chk_not_self_knows CHECK (from_emp <> to_emp)
);

CREATE INDEX idx_knows_to ON knows(to_emp);
CREATE INDEX idx_knows_type ON knows(connection_type);

-- ============================================================
-- 7. AUDIT_LOG (cho Trigger)
-- ============================================================
CREATE TABLE audit_log (
  log_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name      VARCHAR2(50),
  action          VARCHAR2(20),          -- INSERT / UPDATE / DELETE
  record_id       VARCHAR2(100),
  old_value       VARCHAR2(4000),
  new_value       VARCHAR2(4000),
  changed_by      VARCHAR2(100) DEFAULT USER,
  changed_at      TIMESTAMP DEFAULT SYSTIMESTAMP
);

COMMIT;

